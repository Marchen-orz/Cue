// scenePrompt 注入 system 提示词的场景段落，启动时构建一次
var scenePrompt = buildScenePrompt()

// GetScenePrompt 返回全部题型场景及自动选用规则。
// 模型看过截图后按题型自行选用匹配的场景，无需用户手动指定。
func GetScenePrompt() string { return scenePrompt }

func buildScenePrompt() string {
	ids := make([]string, len(scenes))
	for i, s := range scenes {
		ids[i] = s.ID
	}

	var b strings.Builder
	b.WriteString("<ScenePrompt>\n")
	b.WriteString("  <Router>\n")
	b.WriteString("    截图可能是各种类型的题目或内容。作答前先判断题型，从下列场景中选出最匹配的一个，严格按其「作答要求」输出。\n")
	b.WriteString("    - 直接给出答案，不要在回答中提及「场景」「模板」「路由」或场景编号，也不要复述判断过程。\n")
	b.WriteString("    - 一张截图含多道题时，逐题各自判断题型并分别作答，按题号顺序输出。\n")
	fmt.Fprintf(&b, "    - 同时符合多个场景时，按优先级取靠前者：%s。\n", strings.Join(ids, " > "))
	b.WriteString("  </Router>\n")
	for _, s := range scenes {
		fmt.Fprintf(&b, "  <Scene id=%q name=%q>\n", s.ID, s.Name)
		fmt.Fprintf(&b, "    <When>%s</When>\n", s.When)
		b.WriteString("    <Requirements>\n")
		for _, line := range strings.Split(s.Requirements, "\n") {
			b.WriteString("      " + line + "\n")
		}
		b.WriteString("    </Requirements>\n")
		b.WriteString("  </Scene>\n")
	}
	b.WriteString("</ScenePrompt>")
	return b.String()
}
